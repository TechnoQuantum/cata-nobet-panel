"""Generate src/glyphs_data.rs from GNU Unifont (SIL OFL 1.1).

The bitmaps are rendered exactly the way pypixelcolor 0.5.0 renders text for
16-pixel-high panels (font size 16, origin (0, 0), threshold > 128, 8 or 16
pixel cells), so the Rust app sends the same glyph pixels the panel already
displayed correctly with the Python release.

Usage:  py -3 -I tools/extract_unifont_glyphs.py <path-to-unifont.otf> src/glyphs_data.rs
"""
import sys
import unicodedata
from PIL import Image, ImageDraw, ImageFont

HEIGHT = 16

CHARS = [chr(c) for c in range(0x20, 0x7F)]
CHARS += [chr(c) for c in range(0xA0, 0x180)]
CHARS += list("–—‘’‚“”„•…€₺·°′″←→↑↓✓✔×÷")


def render(font, ch):
    probe = ImageDraw.Draw(Image.new("L", (100, HEIGHT), 0))
    bbox = probe.textbbox((0, 0), ch, font=font)
    text_width = bbox[2] - bbox[0]
    wide = unicodedata.east_asian_width(ch) in ("W", "F") or text_width > int(8 * 1.25)
    width = 16 if wide else 8
    img = Image.new("L", (width, HEIGHT), 0)
    ImageDraw.Draw(img).text((0, 0), ch, fill=255, font=font)
    rows = []
    for y in range(HEIGHT):
        value = 0
        for x in range(width):
            if img.getpixel((x, y)) > 128:
                value |= 1 << (15 - x)
        rows.append(value)
    return wide, rows


def main():
    font = ImageFont.truetype(sys.argv[1], HEIGHT)
    lines = [
        "// @generated by tools/extract_unifont_glyphs.py from GNU Unifont (SIL OFL 1.1).",
        "// Each row is 16 bits, pixel x=0 at bit 15. Narrow glyphs use bits 15..8 only.",
        "pub static GLYPHS: &[(char, bool, [u16; 16])] = &[",
    ]
    for ch in sorted(set(CHARS)):
        wide, rows = render(font, ch)
        literal = f"'\\u{{{ord(ch):04x}}}'"
        lines.append(f"    ({literal}, {'true' if wide else 'false'}, [{', '.join(f'0x{r:04x}' for r in rows)}]),")
    lines.append("];")
    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
